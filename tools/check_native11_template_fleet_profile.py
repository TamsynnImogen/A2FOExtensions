#!/usr/bin/env python3
"""Pin reviewed Fleet model-constructor wrappers and the exact Root patch; never execute PE code."""
import argparse
import json
from pathlib import Path

from check_native11_engine_inventory import PE32, EXPECTED_SHA256, digest

ROOT_BASE = 0x400000
ROOT_PATCH_RVA = 0x23faac
ROOT_ORIGINAL = bytes.fromhex('33ff3bc7897dfc740d8b4d0c518bc8e8800afeff')
ROOT_PATCH_PREFIX = bytes.fromhex('90909090908b4d08518b4d0c518bc8')
ROOT_REPLACEMENT_TEMPLATE = ROOT_PATCH_PREFIX + bytes.fromhex('e800000000')
ROOT_CTOR_RVA = 0x220540
ROOT_CTOR_PROLOG = bytes.fromhex('558bec6aff6846b86a00')
FLEET_SHA256 = '3fd18eeee4201a9a1297ac26b3eb88f78c5f72e8c55a62c25179f1d4932e4c11'
FLEET_BASE = 0x5a800000
INNER_RVA, INNER_END = 0x1d4b48, 0x1d4b7c
OUTER_RVA, OUTER_END = 0x1d4b7c, 0x1d4bb4
INNER_BYTES = bytes.fromhex(
    '558bec51894dfc8b450850ff15186aa45a8b55fc8b45fc8b4040c7400c'
    '0000803f33c9894810c64014008bc2595dc204008d4000')
OUTER_BYTES = bytes.fromhex(
    '558bec51894dfc8b450850a17028a15a8b00ffd08b45fc8b55fc8b5240'
    '83c20c8b4d0c890a8b55fc8b524033c9894a10595dc208008d4000')


def region(pe, start, end, expected, fixes_expected, ret_tail, label):
    raw = pe.read(start, end - start)
    if raw != expected or len(raw) != end - start or not raw.startswith(bytes.fromhex('558bec51')):
        raise ValueError(f'{label} body or entry differs')
    if not raw.endswith(bytes.fromhex(ret_tail)):
        raise ValueError(f'{label} return/boundary differs')
    fixes = [rva - start for rva in pe.relocations() if start <= rva < end]
    if fixes != fixes_expected or any(offset + 4 > len(raw) for offset in fixes):
        raise ValueError(f'{label} HIGHLOW relocations differ')
    return dict(rva=start, size=len(raw), bytes_hex=raw.hex(), sha256=digest(raw),
                relocations=fixes)


def checked_root(data):
    if digest(data) != EXPECTED_SHA256:
        raise ValueError('Unsupported Root ArmadaL SHA-256')
    pe = PE32(data)
    if pe.base != ROOT_BASE or pe.read(ROOT_PATCH_RVA, 20) != ROOT_ORIGINAL:
        raise ValueError('Root preferred base or constructor patch bytes differ')
    if pe.read(ROOT_CTOR_RVA, 10) != ROOT_CTOR_PROLOG:
        raise ValueError('Root constructor prolog differs')
    relocations = pe.relocations()
    if [x - ROOT_PATCH_RVA for x in relocations if ROOT_PATCH_RVA <= x < ROOT_PATCH_RVA + 20]:
        raise ValueError('Unexpected Root constructor patch relocation')
    if [x - ROOT_CTOR_RVA for x in relocations if ROOT_CTOR_RVA <= x < ROOT_CTOR_RVA + 10] != [6]:
        raise ValueError('Root constructor prolog HIGHLOW differs')
    if len(ROOT_PATCH_PREFIX) != 15 or ROOT_PATCH_PREFIX[9:] != ROOT_ORIGINAL[9:15]:
        raise ValueError('Reviewed Root replacement prefix differs')
    return dict(patch_rva=ROOT_PATCH_RVA, patch_size=20,
                original_bytes_hex=ROOT_ORIGINAL.hex(), original_sha256=digest(ROOT_ORIGINAL),
                replacement_prefix_hex=ROOT_PATCH_PREFIX.hex(),
                replacement_template_hex=ROOT_REPLACEMENT_TEMPLATE.hex(),
                replacement_rel32='runtime-computed displacement to Fleet outer constructor',
                constructor_rva=ROOT_CTOR_RVA, constructor_prolog_hex=ROOT_CTOR_PROLOG.hex(),
                constructor_prolog_relocations=[6])


def checked_fleet(data):
    if digest(data) != FLEET_SHA256:
        raise ValueError('Unsupported FleetOpsHook SHA-256')
    pe = PE32(data)
    if pe.base != FLEET_BASE:
        raise ValueError('Unexpected FleetOpsHook preferred base')
    inner = region(pe, INNER_RVA, INNER_END, INNER_BYTES, [0x0d],
                   '8bc2595dc204008d4000', 'inner constructor wrapper')
    outer = region(pe, OUTER_RVA, OUTER_END, OUTER_BYTES, [0x0c],
                   '595dc208008d4000', 'outer constructor wrapper')
    if pe.read(OUTER_END, 3) != bytes.fromhex('558bec'):
        raise ValueError('Next Fleet wrapper prolog differs after outer constructor')
    return inner, outer


def header(inner, outer):
    lines = ['// Generated by check_native11_template_fleet_profile.py from exact pinned PE32 images.',
             '#pragma once', '#include <array>', '#include <cstddef>', '#include <cstdint>',
             'namespace a2fo::native11_template_fleet::profile {',
             'struct Region {std::uint32_t rva;const std::uint8_t* bytes;std::size_t size;',
             'const std::uint16_t* relocations;std::size_t relocation_count;};',
             'inline constexpr std::uint32_t root_preferred_base=0x400000;',
             'inline constexpr std::uint32_t root_patch_rva=0x23faac;']
    for name, raw in (('root_original_bytes', ROOT_ORIGINAL),
                      ('root_patch_prefix', ROOT_PATCH_PREFIX),
                      ('root_ctor_prolog', ROOT_CTOR_PROLOG)):
        lines.append('inline constexpr std::array<std::uint8_t,%d> %s{{%s}};' %
                     (len(raw), name, ','.join(f'0x{x:02x}' for x in raw)))
    lines.extend(['inline constexpr std::uint32_t fleet_preferred_base=0x5a800000;',
                  'inline constexpr std::array<std::uint8_t,32> fleet_sha256{{%s}};' %
                  ','.join(f'0x{x:02x}' for x in bytes.fromhex(FLEET_SHA256))])
    for name, item in (('inner_ctor', inner), ('outer_ctor', outer)):
        raw = bytes.fromhex(item['bytes_hex'])
        fixes = item['relocations']
        lines.append('inline constexpr std::array<std::uint8_t,%d> %s_bytes{{%s}};' %
                     (len(raw), name, ','.join(f'0x{x:02x}' for x in raw)))
        lines.append('inline constexpr std::array<std::uint16_t,%d> %s_fixes{{%s}};' %
                     (len(fixes), name, ','.join(map(str, fixes))))
        lines.append('inline constexpr Region %s{0x%x,%s_bytes.data(),%s_bytes.size(),'
                     '%s_fixes.data(),%s_fixes.size()};' %
                     (name, item['rva'], name, name, name, name))
    lines.extend(['inline constexpr std::uint32_t root_ctor_rva=0x220540;', '}'])
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--image', required=True, type=Path)
    parser.add_argument('--fleet-ops', required=True, type=Path)
    parser.add_argument('--header', required=True, type=Path)
    parser.add_argument('--receipt', required=True, type=Path)
    args = parser.parse_args()
    root_data, fleet_data = args.image.read_bytes(), args.fleet_ops.read_bytes()
    root = checked_root(root_data)
    inner, outer = checked_fleet(fleet_data)
    args.header.write_text(header(inner, outer))
    receipt = dict(status='Static pinned Fleet model-constructor profile; no native code executed',
                   root_image=str(args.image.resolve()), root_sha256=digest(root_data),
                   root_preferred_base=ROOT_BASE, root=root,
                   fleet_image=str(args.fleet_ops.resolve()), fleet_sha256=digest(fleet_data),
                   fleet_preferred_base=FLEET_BASE, inner_ctor=inner, outer_ctor=outer,
                   header_sha256=digest(args.header.read_bytes()))
    args.receipt.parent.mkdir(parents=True, exist_ok=True)
    args.receipt.write_text(json.dumps(receipt, indent=2) + '\n')
    print('PASS Fleet constructor profile: Root patch 20; inner', inner['size'],
          'outer', outer['size'], 'bytes; HIGHLOW boundaries checked')


if __name__ == '__main__':
    main()
