#!/usr/bin/env python3
"""Read-only provenance audit of third_party/armada2-refit-native against its
pinned UPSTREAM-MANIFEST.json and, optionally, a checkout of that exact commit.

Usage: refit_provenance_audit.py LOCAL_DIR OUT_DIR [UPSTREAM_CHECKOUT]
Writes OUT_DIR/provenance.json and OUT_DIR/LOCAL-ADAPTATIONS.md. Never writes LOCAL_DIR.
"""
import difflib, hashlib, json, os, subprocess, sys
from pathlib import Path

EXCLUDE_DIRS = {'.git', 'target', 'node_modules', '__pycache__'}
LICENCE_HINTS = ('license', 'licence', 'copying', 'notice', 'third_party_notices', 'authors')

def sha(p): return hashlib.sha256(p.read_bytes()).hexdigest()

def walk(root):
    out = {}
    for d, dirs, files in os.walk(root):
        dirs[:] = sorted(x for x in dirs if x not in EXCLUDE_DIRS)
        for f in files:
            p = Path(d) / f
            if p.is_symlink() or not p.is_file(): continue
            out[p.relative_to(root).as_posix()] = p
    return out

def text(p):
    b = p.read_bytes()
    if b'\0' in b[:8192]: return None
    try: return b.decode('utf-8').splitlines()
    except UnicodeDecodeError: return b.decode('latin-1').splitlines()

def main():
    local, out = Path(sys.argv[1]).resolve(), Path(sys.argv[2]); out.mkdir(parents=True, exist_ok=True)
    upstream = Path(sys.argv[3]).resolve() if len(sys.argv) > 3 else None
    manifest = json.loads((local / 'UPSTREAM-MANIFEST.json').read_text())
    mfiles = manifest['files']; lfiles = walk(local)
    rec = {'repository': manifest['repository'], 'commit': manifest['commit'],
           'archive_sha256': manifest['archive_sha256'], 'manifest_sha256': sha(local / 'UPSTREAM-MANIFEST.json'),
           'excluded_dirs': sorted(EXCLUDE_DIRS)}
    # 1. Manifest self-check against the real upstream commit, when supplied.
    if upstream:
        head = subprocess.run(['git', '-C', str(upstream), 'rev-parse', 'HEAD'], capture_output=True, text=True).stdout.strip()
        ufiles = walk(upstream)
        bad = sorted(k for k, v in mfiles.items() if k in ufiles and sha(ufiles[k]) != v['sha256'])
        rec['upstream_check'] = {'checkout_head': head, 'head_matches_manifest': head == manifest['commit'],
            'upstream_files': len(ufiles), 'manifest_files': len(mfiles),
            'in_manifest_not_upstream': sorted(set(mfiles) - set(ufiles)),
            'in_upstream_not_manifest': sorted(set(ufiles) - set(mfiles)),
            'manifest_hash_mismatches': bad}
    # 2. Local classification.
    unchanged, modified, missing = [], [], []
    for k, v in sorted(mfiles.items()):
        p = lfiles.get(k)
        if p is None: missing.append(k); continue
        h = sha(p)
        (unchanged if h == v['sha256'] else modified).append(k)
    added = sorted(set(lfiles) - set(mfiles))
    mods = []
    for k in modified:
        m = {'path': k, 'upstream_sha256': mfiles[k]['sha256'], 'local_sha256': sha(lfiles[k]), 'local_size': lfiles[k].stat().st_size}
        if upstream and (upstream / k).is_file():
            a, b = text(upstream / k), text(lfiles[k])
            if a is not None and b is not None:
                plus = minus = 0
                for line in difflib.unified_diff(a, b, lineterm='', n=0):
                    if line.startswith('+') and not line.startswith('+++'): plus += 1
                    elif line.startswith('-') and not line.startswith('---'): minus += 1
                m.update({'lines_added': plus, 'lines_removed': minus})
                (out / 'diffs').mkdir(exist_ok=True)
                (out / 'diffs' / (k.replace('/', '__') + '.diff')).write_text(
                    '\n'.join(difflib.unified_diff(a, b, 'upstream/' + k, 'local/' + k, lineterm='')) + '\n')
            else: m['binary'] = True
        mods.append(m)
    adds = [{'path': k, 'sha256': sha(lfiles[k]), 'size': lfiles[k].stat().st_size} for k in added]
    lic = sorted(k for k in set(mfiles) | set(lfiles) if any(h in Path(k).name.lower() for h in LICENCE_HINTS))
    rec.update({'counts': {'manifest': len(mfiles), 'local': len(lfiles), 'unchanged': len(unchanged),
                           'modified': len(modified), 'missing': len(missing), 'added': len(added)},
                'modified': mods, 'missing': missing, 'added': adds,
                'licence_files': [{'path': k, 'in_manifest': k in mfiles, 'present_locally': k in lfiles,
                                   'unchanged': k in unchanged} for k in lic]})
    (out / 'provenance.json').write_text(json.dumps(rec, indent=2) + '\n')
    # 3. Human summary.
    L = ['# armada2-refit-native local adaptations', '',
         f"Upstream `{rec['repository']}` @ `{rec['commit']}`; manifest SHA-256 `{rec['manifest_sha256']}`.",
         f"Generated by `tools/refit_provenance_audit.py` (read-only). Excluded directories: {', '.join(rec['excluded_dirs'])}.", '']
    if upstream:
        u = rec['upstream_check']
        L += ['## Manifest self-check against the pinned commit', '',
              f"- checkout HEAD matches manifest commit: **{u['head_matches_manifest']}**",
              f"- manifest files {u['manifest_files']}, upstream files {u['upstream_files']}; hash mismatches **{len(u['manifest_hash_mismatches'])}**",
              f"- in manifest but not upstream: {len(u['in_manifest_not_upstream'])}; in upstream but not manifest: {len(u['in_upstream_not_manifest'])} {u['in_upstream_not_manifest'][:10]}", '']
    c = rec['counts']
    L += ['## Local state', '', f"| unchanged | modified | missing | added |", '|---:|---:|---:|---:|',
          f"| {c['unchanged']} | {c['modified']} | {c['missing']} | {c['added']} |", '', '## Modified upstream files', '',
          '| Path | +lines | -lines | local SHA-256 |', '|---|---:|---:|---|']
    for m in mods:
        L.append(f"| `{m['path']}` | {m.get('lines_added', 'bin' if m.get('binary') else '?')} | {m.get('lines_removed', '')} | `{m['local_sha256'][:16]}…` |")
    L += ['', '## Added local files', '', '| Path | Size | SHA-256 |', '|---|---:|---|']
    for a in adds: L.append(f"| `{a['path']}` | {a['size']} | `{a['sha256'][:16]}…` |")
    L += ['', '## Missing upstream files', ''] + ([f'- `{k}`' for k in missing] or ['none'])
    L += ['', '## Licence and notice files', '', '| Path | In manifest | Present | Unchanged |', '|---|---|---|---|']
    for l in rec['licence_files']: L.append(f"| `{l['path']}` | {l['in_manifest']} | {l['present_locally']} | {l['unchanged']} |")
    (out / 'LOCAL-ADAPTATIONS.md').write_text('\n'.join(L) + '\n')
    print(json.dumps(c))

if __name__ == '__main__': main()
