#!/usr/bin/env python3
"""Pin read-only Craft preparation sources. Never starts or executes the game."""
import argparse,json,struct
from pathlib import Path
from check_native11_engine_inventory import PE32,EXPECTED_SHA256,digest
RANGES={'entity_prepare_dispatch':(0xd54e0,0xd550f),
        'craft_prepare':(0xcb390,0xcb4d4),'race_hull_divisor':(0xaf100,0xaf10d),
        'zero':(0x2ae15c,0x2ae160),'one':(0x2ae218,0x2ae21c),
        'borg_name':(0x304458,0x30445d)}
SLOTS=((0x2b3e64,0xcb390),(0x2b3d08,0xd54e0),(0x2b3de4,0xaf100))
def main():
 ap=argparse.ArgumentParser(description=__doc__)
 ap.add_argument('--image',required=True,type=Path);ap.add_argument('--header',required=True,type=Path)
 ap.add_argument('--receipt',required=True,type=Path);a=ap.parse_args()
 data=a.image.read_bytes()
 if digest(data)!=EXPECTED_SHA256:raise ValueError('unsupported preparation input image')
 pe=PE32(data)
 if pe.base!=0x400000:raise ValueError('unsupported preparation image base')
 if pe.read(0xaf100,13)!=bytes.fromhex('8b81fc000000d98088020000c3'):raise ValueError('race hull getter differs')
 if pe.read(0x2ae15c,4)!=struct.pack('<f',0) or pe.read(0x2ae218,4)!=struct.pack('<f',1):raise ValueError('hull normalization constants differ')
 if pe.read(0x304458,5)!=b'borg\0':raise ValueError('special-race lookup differs')
 relocs=pe.relocations();regions=[]
 for name,(start,end) in RANGES.items():
  if not 0<end-start<=512:raise ValueError('preparation region exceeds bound')
  if any(start-3<=r<start or end-3<=r<end for r in relocs):raise ValueError('straddling preparation relocation')
  raw=pe.read(start,end-start);fixes=[r-start for r in relocs if start<=r<end]
  regions.append(dict(name=name,rva=start,size=len(raw),bytes_hex=raw.hex(),sha256=digest(raw),relocations=fixes))
 for rva,target in SLOTS:
  if pe.read(rva,4)!=struct.pack('<I',pe.base+target):raise ValueError('preparation slot differs')
 lines=['// Generated by check_native11_craft_preparation_profile.py from the pinned Root image.',
 '#pragma once','#include <array>','#include <cstdint>','#include <cstddef>',
 'namespace a2fo::native11_craft_preparation::profile {',
 'struct Region {std::uint32_t rva;const std::uint8_t* bytes;std::size_t size;const std::uint16_t* relocations;std::size_t relocation_count;};',
 'inline constexpr std::uint32_t preferred_base=0x400000;']
 for r in regions:
  name=r['name'];raw=bytes.fromhex(r['bytes_hex'])
  lines.append('inline constexpr std::array<std::uint8_t,%d> %s_bytes{{%s}};'%(len(raw),name,','.join('0x%02x'%x for x in raw)))
  lines.append('inline constexpr std::array<std::uint16_t,%d> %s_fixes{{%s}};'%(len(r['relocations']),name,','.join(map(str,r['relocations']))))
 lines.append('inline constexpr std::array<Region,%d> regions{{'%len(regions))
 for r in regions:
  n=r['name'];lines.append('{0x%x,%s_bytes.data(),%s_bytes.size(),%s_fixes.data(),%s_fixes.size()},'%(r['rva'],n,n,n,n))
 lines+=['}};','inline constexpr std::array<std::array<std::uint32_t,2>,3> slots{{']
 for rva,target in SLOTS:lines.append('{{0x%x,0x%x}},'%(rva,target))
 lines+=['}};','// Base setup depends on these regions, not the separate entity display wrapper.',
 'inline constexpr std::array<Region,5> logical_regions{{']
 for r in regions:
  if r['name']=='entity_prepare_dispatch':continue
  n=r['name'];lines.append('{0x%x,%s_bytes.data(),%s_bytes.size(),%s_fixes.data(),%s_fixes.size()},'%(r['rva'],n,n,n,n))
 lines+=['}};','inline constexpr std::array<std::array<std::uint32_t,2>,1> logical_slots{{{{0x2b3e64,0xcb390}}}};','}'];a.header.write_text('\n'.join(lines)+'\n')
 a.receipt.write_text(json.dumps(dict(status='Static preparation profile; no execution or live freshness acceptance',image=str(a.image.resolve()),image_sha256=EXPECTED_SHA256,regions=regions,slots=SLOTS,header_sha256=digest(a.header.read_bytes()),native_code_executed=False),indent=2)+'\n')
 print('PASS pinned preparation profile:',len(regions),'regions and',len(SLOTS),'slots; no native execution')
if __name__=='__main__':main()
