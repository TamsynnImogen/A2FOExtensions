#!/usr/bin/env python3
"""Pin the native database/texture destructor boundaries; read PE data only, never execute game code."""
import argparse
import json
from pathlib import Path
from check_native11_engine_inventory import PE32, EXPECTED_SHA256, digest

# End-exclusive reviewed native destructor bodies.
RANGES = {
    'database_destroy': (0x220690, 0x22074e),
    'texture_destroy': (0x2427d0, 0x242862),
}
FLEET_SHA256='3fd18eeee4201a9a1297ac26b3eb88f78c5f72e8c55a62c25179f1d4932e4c11'
FLEET_BASE=0x5a800000
FLEET_WRAPPER_RVA=0x1d4bb4
FLEET_ORIGINAL_SLOT_RVA=0x246a1c
FLEET_WRAPPER_BYTES=bytes.fromhex(
    '558bec51894dfc8b45fc8b4040ff48108b45fc8b4040837810007f13'
    '8b4dfcff151c6aa45a8b45fc50e87ad0000059595dc3')

def checked_fleet(data):
    if digest(data)!=FLEET_SHA256:raise ValueError('Unsupported FleetOpsHook input DLL')
    pe=PE32(data)
    if pe.base!=FLEET_BASE:raise ValueError('Unexpected FleetOpsHook image base')
    raw=pe.read(FLEET_WRAPPER_RVA,0x1d4be6-FLEET_WRAPPER_RVA)
    if raw!=FLEET_WRAPPER_BYTES:raise ValueError('Fleet destructor wrapper bytes differ')
    fixes=[place-FLEET_WRAPPER_RVA for place in pe.relocations()
           if FLEET_WRAPPER_RVA<=place<FLEET_WRAPPER_RVA+len(raw)]
    if fixes!=[0x21]:raise ValueError('Fleet destructor wrapper HIGHLOW differs')
    return dict(rva=FLEET_WRAPPER_RVA,size=len(raw),bytes_hex=raw.hex(),
                sha256=digest(raw),relocations=fixes)

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--image',required=True,type=Path)
    parser.add_argument('--header',required=True,type=Path)
    parser.add_argument('--receipt',required=True,type=Path)
    parser.add_argument('--fleet-ops',type=Path)
    args=parser.parse_args()
    data=args.image.read_bytes()
    if digest(data)!=EXPECTED_SHA256: raise ValueError('Unsupported lifecycle input image')
    pe=PE32(data)
    if pe.base!=0x400000: raise ValueError('Unexpected image base')
    fleet=checked_fleet(args.fleet_ops.read_bytes()) if args.fleet_ops else None
    relocations=pe.relocations()
    regions=[]
    for name,(start,end) in RANGES.items():
        cursor=start;index=0
        while cursor<end:
            stop=min(cursor+480,end)
            for relocation in relocations:
                if relocation<stop<relocation+4: stop=relocation
            if stop<=cursor: raise ValueError('Relocation split made no progress')
            raw=pe.read(cursor,stop-cursor)
            fixes=[place-cursor for place in relocations if cursor<=place<stop]
            if any(offset+4>len(raw) for offset in fixes): raise ValueError('Split HIGHLOW')
            regions.append(dict(name=f'{name}_{index}',rva=cursor,size=len(raw),
                bytes_hex=raw.hex(),sha256=digest(raw),relocations=fixes))
            cursor=stop;index+=1
    lines=['// Generated by check_native11_lifecycle_profile.py from the exact pinned image.',
        '#pragma once','#include <array>','#include <cstdint>','#include <cstddef>',
        'namespace a2fo::native11_lifecycle::lifecycle_profile {',
        'struct Region {std::uint32_t rva;const std::uint8_t* bytes;std::size_t size;',
        'const std::uint16_t* relocations;std::size_t relocation_count;};',
        'inline constexpr std::uint32_t preferred_base=0x400000;']
    for region in regions:
        name=region['name'];raw=bytes.fromhex(region['bytes_hex']);fixes=region['relocations']
        lines.append('inline constexpr std::array<std::uint8_t,%d> %s_bytes{{%s}};'%
            (len(raw),name,','.join(f'0x{x:02x}' for x in raw)))
        lines.append('inline constexpr std::array<std::uint16_t,%d> %s_fixes{{%s}};'%
            (len(fixes),name,','.join(map(str,fixes))))
    lines.append('inline constexpr std::array<Region,%d> regions{{'%len(regions))
    for region in regions:
        name=region['name']
        lines.append('{0x%x,%s_bytes.data(),%s_bytes.size(),%s_fixes.data(),%s_fixes.size()},'%
            (region['rva'],name,name,name,name))
    lines.append('}};')
    lines.append('inline constexpr std::uint32_t fleet_preferred_base=0x5a800000;')
    lines.append('inline constexpr std::uint32_t fleet_original_slot_rva=0x246a1c;')
    lines.append('inline constexpr std::uint32_t fleet_wrapper_rva=0x1d4bb4;')
    fleet_hash=bytes.fromhex(FLEET_SHA256) if fleet else bytes(32)
    lines.append('inline constexpr std::array<std::uint8_t,32> fleet_sha256{{%s}};'%
        ','.join(f'0x{x:02x}' for x in fleet_hash))
    lines.append('inline constexpr bool fleet_available=%s;'%('true' if fleet else 'false'))
    if fleet:
        raw=bytes.fromhex(fleet['bytes_hex']);fixes=fleet['relocations']
        lines.append('inline constexpr std::array<std::uint8_t,%d> fleet_wrapper_bytes{{%s}};'%
            (len(raw),','.join(f'0x{x:02x}' for x in raw)))
        lines.append('inline constexpr std::array<std::uint16_t,%d> fleet_wrapper_fixes{{%s}};'%
            (len(fixes),','.join(map(str,fixes))))
        lines.append('inline constexpr Region fleet_wrapper{0x%x,fleet_wrapper_bytes.data(),'
            'fleet_wrapper_bytes.size(),fleet_wrapper_fixes.data(),fleet_wrapper_fixes.size()};'%
            fleet['rva'])
    else:
        lines.append('inline constexpr Region fleet_wrapper{0,nullptr,0,nullptr,0};')
    lines.append('}')
    args.header.write_text('\n'.join(lines)+'\n')
    result=dict(status='Static pinned lifecycle profile; no game code executed',
        image=str(args.image.resolve()),image_sha256=digest(data),regions=regions,
        fleet_ops=({'image':str(args.fleet_ops.resolve()),'image_sha256':FLEET_SHA256,
                    'preferred_base':FLEET_BASE,'wrapper':fleet,
                    'original_slot_rva':FLEET_ORIGINAL_SLOT_RVA,
                    'original_slot_file_backed':False} if fleet else None),
        header_sha256=digest(args.header.read_bytes()))
    args.receipt.parent.mkdir(parents=True,exist_ok=True)
    args.receipt.write_text(json.dumps(result,indent=2)+'\n')
    print('PASS lifecycle profile:',len(regions),'regions; Fleet wrapper',bool(fleet),
          '; HIGHLOW normalization boundaries checked')

if __name__=='__main__': main()
