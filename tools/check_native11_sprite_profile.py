#!/usr/bin/env python3
"""Pin reviewed sprite code/data in one PE32 image; never execute game code."""
import argparse
import json
from pathlib import Path

from check_native11_engine_inventory import PE32, EXPECTED_SHA256, digest

# Lead-reviewed, end-exclusive RVAs. Keep each inspected code region <=480 bytes.
RANGES = {
    'clip2d': (0x23b1c0, 0x23b4aa),
    'colour': (0x2254a0, 0x2254f5),
    'sprite_quad': (0x225590, 0x22576d),
    'get_texture': (0x23b150, 0x23b154),
    'refresh': (0x224630, 0x224743),
    'device_dimensions': (0x2215f0, 0x221668),
    'mode_dimension_owner': (0x2233c0, 0x2233db),
}
CONSTANTS = {
    'colour_scale': (0x2ae698, bytes.fromhex('00007f43')),
    'colour_bias': (0x2bc6a0, bytes.fromhex('0000000000003843')),
}
SLOTS = {
    'colour': (0x2bc6ac + 0x88, 0x2254a0),
    'sprite_quad': (0x2bc6ac + 0xc4, 0x225590),
    'sprite_first': (0x2bcb34, 0x23b190),
    'device_mode_dimensions': (0x2bc6ac + 0x0c, 0x2233c0),
}
FLEET_SHA256 = '3fd18eeee4201a9a1297ac26b3eb88f78c5f72e8c55a62c25179f1d4932e4c11'
FLEET_CALLBACK_RVA = 0x1f155c
FLEET_CALLBACK_BYTES = bytes.fromhex(
    '558beca1ac18a15a833800740ca1ac18a15a8b00e81f1cf8ff8b4508508b00'
    'ff90a80000005dc20400')


def generate(data):
    if digest(data) != EXPECTED_SHA256:
        raise ValueError('Unsupported sprite input image')
    pe = PE32(data)
    if pe.base != 0x400000:
        raise ValueError('Unexpected PE32 preferred image base')
    if pe.read(0x23b1c0, 6) != bytes.fromhex('558bec83ec14'):
        raise ValueError('Unexpected ClipAndRender2D prolog')
    if pe.read(0x23b486, 6) != bytes.fromhex('ff92c4000000'):
        raise ValueError('Unexpected ClipAndRender2D sprite call')
    relocations = pe.relocations()
    regions = []
    for name, (start, end) in RANGES.items():
        if not start < end:
            raise ValueError('Empty reviewed sprite range')
        cursor, index = start, 0
        while cursor < end:
            stop = min(cursor + 480, end)
            for relocation in relocations:
                if relocation < stop < relocation + 4:
                    stop = relocation
            if stop <= cursor:
                raise ValueError('Relocation split made no progress')
            raw = pe.read(cursor, stop - cursor)
            fixes = [place - cursor for place in relocations if cursor <= place < stop]
            if any(offset + 4 > len(raw) for offset in fixes):
                raise ValueError('Split HIGHLOW relocation')
            regions.append(dict(name=f'{name}_{index}', rva=cursor, size=len(raw),
                                bytes_hex=raw.hex(), sha256=digest(raw), relocations=fixes))
            cursor, index = stop, index + 1
    constants = []
    for name, (rva, expected) in CONSTANTS.items():
        actual = pe.read(rva, len(expected))
        if actual != expected:
            raise ValueError(f'Unexpected {name} constant bytes')
        if any(rva <= place < rva + len(actual) for place in relocations):
            raise ValueError(f'Unexpected {name} constant relocation')
        constants.append(dict(name=name, rva=rva, bytes_hex=actual.hex(), sha256=digest(actual)))
        regions.append(dict(name=f'{name}_0', rva=rva, size=len(actual),
                            bytes_hex=actual.hex(), sha256=digest(actual), relocations=[]))
    slots = []
    for name, (rva, target_rva) in SLOTS.items():
        raw = pe.read(rva, 4)
        if int.from_bytes(raw, 'little') != pe.base + target_rva:
            raise ValueError(f'Unexpected {name} vtable target')
        if rva not in relocations:
            raise ValueError(f'Missing {name} vtable HIGHLOW relocation')
        slots.append(dict(name=name, rva=rva, target_rva=target_rva,
                          bytes_hex=raw.hex(), sha256=digest(raw)))
    return regions, constants, slots


def generate_fleet(data):
    if digest(data) != FLEET_SHA256:
        raise ValueError('Unsupported FleetOpsHook input DLL')
    pe = PE32(data)
    if pe.base != 0x5a800000:
        raise ValueError('Unexpected FleetOpsHook PE32 preferred base')
    raw = pe.read(FLEET_CALLBACK_RVA, 0x1f1585 - FLEET_CALLBACK_RVA)
    if raw != FLEET_CALLBACK_BYTES:
        raise ValueError('Unexpected FleetOpsHook sprite callback bytes')
    fixes = [place - FLEET_CALLBACK_RVA for place in pe.relocations()
             if FLEET_CALLBACK_RVA <= place < FLEET_CALLBACK_RVA + len(raw)]
    if fixes != [4, 0xe]:
        raise ValueError('Unexpected FleetOpsHook callback HIGHLOW offsets')
    return dict(rva=FLEET_CALLBACK_RVA, size=len(raw), bytes_hex=raw.hex(),
                sha256=digest(raw), relocations=fixes)


def header(regions, constants, slots, fleet=None):
    lines = ['// Generated by check_native11_sprite_profile.py from the exact pinned image.',
             '#pragma once', '#include <array>', '#include <cstdint>', '#include <cstddef>',
             'namespace a2fo::native11_sprites::profile {',
             'struct Region {std::uint32_t rva;const std::uint8_t* bytes;std::size_t size;',
             'const std::uint16_t* relocations;std::size_t relocation_count;};',
             'struct Constant {std::uint32_t rva;const std::uint8_t* bytes;std::size_t size;};',
             'struct Slot {std::uint32_t rva,target_rva;};',
             'inline constexpr std::uint32_t preferred_base=0x400000;']
    for region in regions:
        name = region['name']
        raw = bytes.fromhex(region['bytes_hex'])
        fixes = region['relocations']
        lines.append('inline constexpr std::array<std::uint8_t,%d> %s_bytes{{%s}};' %
                     (len(raw), name, ','.join(f'0x{x:02x}' for x in raw)))
        lines.append('inline constexpr std::array<std::uint16_t,%d> %s_fixes{{%s}};' %
                     (len(fixes), name, ','.join(map(str, fixes))))
    lines.append('inline constexpr std::array<Region,%d> regions{{' % len(regions))
    for region in regions:
        name = region['name']
        lines.append('{0x%x,%s_bytes.data(),%s_bytes.size(),%s_fixes.data(),%s_fixes.size()},' %
                     (region['rva'], name, name, name, name))
    lines.append('}};')
    lines.append('inline constexpr std::array<Constant,%d> constants{{' % len(constants))
    for constant in constants:
        name = constant['name']
        lines.append('{0x%x,%s_0_bytes.data(),%s_0_bytes.size()},' %
                     (constant['rva'], name, name))
    lines.append('}};')
    lines.append('inline constexpr std::array<Slot,%d> slots{{' % len(slots))
    for slot in slots:
        lines.append('{0x%x,0x%x},' % (slot['rva'], slot['target_rva']))
    lines.append('}};')
    lines.append('inline constexpr std::uint32_t fleet_preferred_base=0x5a800000;')
    fleet_hash = bytes.fromhex(FLEET_SHA256) if fleet else bytes(32)
    lines.append('inline constexpr std::array<std::uint8_t,32> fleet_sha256{{%s}};' %
                 ','.join(f'0x{x:02x}' for x in fleet_hash))
    lines.append('inline constexpr bool fleet_callback_available=%s;' %
                 ('true' if fleet else 'false'))
    if fleet:
        raw = bytes.fromhex(fleet['bytes_hex'])
        fixes = fleet['relocations']
        lines.append('inline constexpr std::array<std::uint8_t,%d> fleet_callback_bytes{{%s}};' %
                     (len(raw), ','.join(f'0x{x:02x}' for x in raw)))
        lines.append('inline constexpr std::array<std::uint16_t,%d> fleet_callback_fixes{{%s}};' %
                     (len(fixes), ','.join(map(str, fixes))))
        lines.append('inline constexpr Region fleet_callback{0x%x,fleet_callback_bytes.data(),'
                     'fleet_callback_bytes.size(),fleet_callback_fixes.data(),fleet_callback_fixes.size()};' %
                     fleet['rva'])
    else:
        lines.append('inline constexpr Region fleet_callback{0,nullptr,0,nullptr,0};')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--image', required=True, type=Path)
    parser.add_argument('--fleet-ops', type=Path)
    parser.add_argument('--header', required=True, type=Path)
    parser.add_argument('--receipt', required=True, type=Path)
    args = parser.parse_args()
    data = args.image.read_bytes()
    regions, constants, slots = generate(data)
    fleet = generate_fleet(args.fleet_ops.read_bytes()) if args.fleet_ops else None
    args.header.write_text(header(regions, constants, slots, fleet))
    args.receipt.parent.mkdir(parents=True, exist_ok=True)
    args.receipt.write_text(json.dumps({
        'status': 'Static pinned sprite profile; no game code executed',
        'image': str(args.image.resolve()), 'image_sha256': digest(data),
        'regions': regions, 'constants': constants, 'slots': slots,
        'fleet_ops': ({'image': str(args.fleet_ops.resolve()),
                       'image_sha256': FLEET_SHA256, 'preferred_base': 0x5a800000,
                       'callback': fleet} if fleet else None),
        'header_sha256': digest(args.header.read_bytes())}, indent=2) + '\n')
    print('PASS sprite profile:', len(regions), 'regions;', len(constants),
          'constants;', len(slots), 'vtable slots; FleetOps callback', bool(fleet),
          '; HIGHLOW boundaries checked')


if __name__ == '__main__':
    main()
