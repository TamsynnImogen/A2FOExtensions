#!/usr/bin/env python3
"""Pin the reviewed FOFS fopen callback and Root import call; never execute either image."""
import argparse
import json
from pathlib import Path

from check_native11_engine_inventory import PE32, EXPECTED_SHA256, digest

FLEET_SHA256 = '3fd18eeee4201a9a1297ac26b3eb88f78c5f72e8c55a62c25179f1d4932e4c11'
FLEET_BASE = 0x5a800000
CALLBACK_START, CALLBACK_END = 0x106920, 0x1069fc
CALLBACK_BYTES = bytes.fromhex(
    '558bec6a006a0053565733c05568eb69905a64ff3064892033dba18019a15a'
    '8b008b40188b70084e85f67c4e4633ffa18019a15a8b008b40188bd7e86c'
    'a0f7ff8b4004508d45f88b5508e841efefff8b4df88d45fc5ae855f0efff'
    '8b450c508b45fce8c1f1efff50e84f55ffff83c4088bd885db7504474e75'
    'b585db75328b450850e805e5ffff83f8011bc04084c0740da1e41ea15a8b'
    '008078080075128b450c508b450850e81155ffff83c4088bd833c05a595964'
    '891068f269905a8d45f8ba02000000e8f2ecefffc3e9f4e3efffebeb8bc35f'
    '5e5b59595dc390')
CALLBACK_FIXES = [0x0e, 0x1b, 0x30, 0x92, 0xb9]
ROOT_BASE = 0x400000
OPEN_CALL_RVA = 0x240162
OPEN_CALL_BYTES = bytes.fromhex('ff158c7f7b00')
FOPEN_IAT_RVA = 0x3b7f8c


def checked_fleet(data):
    if digest(data) != FLEET_SHA256:
        raise ValueError('Unsupported FleetOpsHook SHA-256')
    pe = PE32(data)
    if pe.base != FLEET_BASE:
        raise ValueError('Unexpected FleetOpsHook preferred base')
    raw = pe.read(CALLBACK_START, CALLBACK_END - CALLBACK_START)
    if len(CALLBACK_BYTES) != 220 or raw != CALLBACK_BYTES:
        raise ValueError('FOFS fopen callback body differs')
    if not raw.startswith(bytes.fromhex('558bec6a006a00535657')) or \
            not raw.endswith(bytes.fromhex('8bc35f5e5b59595dc390')) or \
            pe.read(CALLBACK_END, 5) != bytes.fromhex('558bec6a00'):
        raise ValueError('FOFS callback entry, return or next-function boundary differs')
    fixes = [rva - CALLBACK_START for rva in pe.relocations()
             if CALLBACK_START <= rva < CALLBACK_END]
    if fixes != CALLBACK_FIXES or any(offset + 4 > len(raw) for offset in fixes):
        raise ValueError('FOFS callback HIGHLOW relocations differ')
    return dict(rva=CALLBACK_START, size=len(raw), bytes_hex=raw.hex(),
                sha256=digest(raw), relocations=fixes)


def checked_root(data):
    if digest(data) != EXPECTED_SHA256:
        raise ValueError('Unsupported Root ArmadaL SHA-256')
    pe = PE32(data)
    if pe.base != ROOT_BASE or pe.read(OPEN_CALL_RVA, 6) != OPEN_CALL_BYTES:
        raise ValueError('Root fopen call or preferred base differs')
    if pe.imports().get(FOPEN_IAT_RVA) != ('MSVCRT.dll', 'fopen'):
        raise ValueError('Root fopen IAT import identity differs')
    fixes = [rva - OPEN_CALL_RVA for rva in pe.relocations()
             if OPEN_CALL_RVA <= rva < OPEN_CALL_RVA + 6]
    if fixes != [2]:
        raise ValueError('Root fopen call HIGHLOW relocation differs')
    return dict(rva=OPEN_CALL_RVA, size=6, bytes_hex=OPEN_CALL_BYTES.hex(),
                sha256=digest(OPEN_CALL_BYTES), relocations=fixes,
                import_iat_rva=FOPEN_IAT_RVA,
                import_dll='MSVCRT.dll', import_name='fopen')


def header(fleet):
    raw = bytes.fromhex(fleet['bytes_hex'])
    fixes = fleet['relocations']
    lines = [
        '// Generated by check_native11_fofs_stream_profile.py from exact pinned PE32 images.',
        '#pragma once', '#include <array>', '#include <cstddef>', '#include <cstdint>',
        'namespace a2fo::native11_fofs_stream::profile {',
        'struct Region {std::uint32_t rva;const std::uint8_t* bytes;std::size_t size;',
        'const std::uint16_t* relocations;std::size_t relocation_count;};',
        'inline constexpr std::uint32_t fleet_preferred_base=0x5a800000;',
        'inline constexpr std::array<std::uint8_t,32> fleet_sha256{{%s}};' %
        ','.join(f'0x{x:02x}' for x in bytes.fromhex(FLEET_SHA256)),
        'inline constexpr std::array<std::uint8_t,%d> fopen_callback_bytes{{%s}};' %
        (len(raw), ','.join(f'0x{x:02x}' for x in raw)),
        'inline constexpr std::array<std::uint16_t,%d> fopen_callback_fixes{{%s}};' %
        (len(fixes), ','.join(map(str, fixes))),
        'inline constexpr Region fopen_callback{0x106920,fopen_callback_bytes.data(),'
        'fopen_callback_bytes.size(),fopen_callback_fixes.data(),fopen_callback_fixes.size()};',
        'inline constexpr std::uint32_t root_preferred_base=0x400000;',
        'inline constexpr std::uint32_t open_call_rva=0x240162;',
        'inline constexpr std::array<std::uint8_t,6> open_call_bytes{{%s}};' %
        ','.join(f'0x{x:02x}' for x in OPEN_CALL_BYTES),
        'inline constexpr std::array<std::uint16_t,1> open_call_fixes{{2}};',
        '}',
    ]
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--image', required=True, type=Path)
    parser.add_argument('--fleet-ops', required=True, type=Path)
    parser.add_argument('--header', required=True, type=Path)
    parser.add_argument('--receipt', required=True, type=Path)
    args = parser.parse_args()
    root_data, fleet_data = args.image.read_bytes(), args.fleet_ops.read_bytes()
    root, fleet = checked_root(root_data), checked_fleet(fleet_data)
    args.header.write_text(header(fleet))
    result = dict(status='Static pinned FOFS stream profile; no native code executed',
                  root_image=str(args.image.resolve()), root_sha256=digest(root_data),
                  root_preferred_base=ROOT_BASE, root_open_call=root,
                  fleet_image=str(args.fleet_ops.resolve()), fleet_sha256=digest(fleet_data),
                  fleet_preferred_base=FLEET_BASE, fleet_fopen_callback=fleet,
                  header_sha256=digest(args.header.read_bytes()))
    args.receipt.parent.mkdir(parents=True, exist_ok=True)
    args.receipt.write_text(json.dumps(result, indent=2) + '\n')
    print('PASS FOFS stream profile: callback', fleet['size'], 'bytes;',
          len(fleet['relocations']), 'HIGHLOW fixes; named Root fopen import')


if __name__ == '__main__':
    main()
