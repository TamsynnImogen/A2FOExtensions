#!/usr/bin/env python3
"""Generate ABI-typed forwarding thunks from MinGW's public D3D8 interface.

Generated output is checked in; the SDK header is only needed to regenerate.
No reference renderer implementation is copied.
"""
import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
INTERFACES = ['IDirect3D8', 'IDirect3DDevice8', 'IDirect3DTexture8',
              'IDirect3DVolumeTexture8', 'IDirect3DCubeTexture8',
              'IDirect3DVertexBuffer8', 'IDirect3DIndexBuffer8',
              'IDirect3DSurface8', 'IDirect3DVolume8', 'IDirect3DSwapChain8']


def generate(header):
    output = ['// Generated by tools/generate_d3d8_observer.py; do not edit.',
              '// Public D3D8 declarations only; all operations forward unchanged.']
    attach = []
    for interface in INTERFACES:
        body = re.search(r'DECLARE_INTERFACE_IID_\(' + interface + r',.*?\n\{(.*?)\n\};', header, re.S).group(1)
        methods = list(re.finditer(r'STDMETHOD(?:_\(([^,]+),\s*(\w+)\s*\)|\((\w+)\))\s*\((.*?)\)\s*PURE', body, re.S))
        assert methods, interface
        for index, method in enumerate(methods):
            ret, name = (method[1].strip(), method[2]) if method[2] else ('HRESULT', method[3])
            raw = re.sub(r'^THIS_?\s*', '', method[4].strip())
            params = [' '.join(p.split()) for p in raw.split(',')] if raw else []
            names = [re.search(r'(\w+)\s*$', p).group(1) for p in params]
            sig = ', '.join([f'{interface}* self', *params])
            args = ', '.join(names)
            before, after = [], []
            if name in ('CreateDevice', 'Reset', 'CreateAdditionalSwapChain'):
                pp = next(n for p, n in zip(params, names) if 'D3DPRESENT_PARAMETERS' in p)
                before.append(f'    call.presentation({pp});')
            if name == 'SetViewport':
                before.append(f'    call.viewport({names[0]});')
            if name in ('SetRenderTarget', 'SetTexture', 'SetStreamSource', 'SetIndices'):
                pass  # Arguments already contain native object identities.
            if name == 'CreateDevice':
                after += [f'    if (SUCCEEDED(result) && {names[-1]} && *{names[-1]}) {{',
                          f'        observe(*{names[-1]}, Kind::IDirect3DDevice8);',
                          f'        remember_device(*{names[-1]}, {names[2]}, {pp});', '    }']
            if name == 'Reset':
                after.append(f'    if (SUCCEEDED(result)) remember_device(self, nullptr, {names[0]});')
            if name == 'QueryInterface' or name == 'GetContainer':
                after.append(f'    if (SUCCEEDED(result) && {names[1]}) observe_iid(*{names[1]}, {names[0]});')
            for p, n in zip(params, names):
                match = re.search(r'(IDirect3D\w*8)\s*\*\s*\*', p)
                if match:
                    kind = match[1]
                    observe_func = 'observe_texture' if kind == 'IDirect3DBaseTexture8' else 'observe'
                    kind_arg = '' if observe_func == 'observe_texture' else f', Kind::{kind}'
                    if name != 'CreateDevice':
                        after.append(f'    if (SUCCEEDED(result) && {n}) {observe_func}(*{n}{kind_arg});')
            if name == 'GetDesc' and interface in ('IDirect3DSurface8', 'IDirect3DTexture8', 'IDirect3DVertexBuffer8', 'IDirect3DIndexBuffer8'):
                after.append(f'    if (SUCCEEDED(result)) call.descriptor({names[0]});')
            if name == 'GetLevelDesc' and interface == 'IDirect3DTexture8':
                after.append(f'    if (SUCCEEDED(result)) call.descriptor({names[1]});')
            if name == 'Release':
                after.append('    if (!result) forget(self, call.record());')
            if interface == 'IDirect3DDevice8' and name == 'CreateVertexShader':
                after.append('    if (SUCCEEDED(result)) capture_shader(call.record(), declaration, byte_code, shader, usage, true);')
            if interface == 'IDirect3DDevice8' and name == 'CreatePixelShader':
                after.append('    if (SUCCEEDED(result)) capture_shader(call.record(), nullptr, byte_code, shader, 0, false);')
            if name == 'Present':
                after.append('    present_boundary(self, result);')
                if interface == 'IDirect3DDevice8':
                    after.append(f'    if (SUCCEEDED(result)) probe_after_present(self, {names[2]});')
            output += [f'static {ret} STDMETHODCALLTYPE hook_{interface}_{name}({sig}) {{',
                       f'    Call call(self, Kind::{interface}, {index}, "{interface}", "{name}");',
                       *[f'    call.argument("{n}", {n});' for n in names], *before,
                       f'    using Function = {ret} (STDMETHODCALLTYPE*)({sig});',
                       '    const auto function = call.original<Function>();']
            # A hook can only be called through a live registered cloned table.
            output.append('    if (!function) std::terminate();')
            invoke = f'function(self{", " if args else ""}{args})'
            if ret == 'void':
                output += [f'    {invoke};', '    call.complete(0);']
            else:
                output += [f'    const auto result = {invoke};', f'    call.complete_result(result, {str(ret == "HRESULT").lower()});', *after, '    return result;']
            output.append('}')
        output += [f'static void* const table_{interface}[] = {{',
                   *[f'    address(&hook_{interface}_{m[2] or m[3]}),' for m in methods], '};',
                   f'static_assert(sizeof(table_{interface}) / sizeof(void*) == {len(methods)});']
        attach.append(f'        case Kind::{interface}: return {{table_{interface}, {len(methods)}}};')
    output += ['static Table hooks_for(Kind kind) {', '    switch (kind) {', *attach,
               '    }', '    return {};', '}']
    return '\n'.join(output) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--header', type=Path, default=Path('/usr/i686-w64-mingw32/sys-root/mingw/include/d3d8.h'))
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'renderer/d3d8_compat/generated_thunks.inl'
    text = generate(args.header.read_text())
    if args.check:
        if target.read_text() != text:
            raise SystemExit('D3D8 thunks differ; regenerate with this script')
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text)


if __name__ == '__main__':
    main()
